"""Generates tools/frost_layout.gd (D-100) from tools/meadow_layout.gd.

The Frostlands (region 2) keeps the Meadowlands' tested ground plan, mirrored
left to right, and dresses it for winter: every prop swaps to an icy
counterpart scaled to a similar footprint, the farm fields, orchard and
training dummies go, the three start-area arenas (Reaper and knights live in
region 1) are left out, and the boss arena and gate move with the mirror.

Usage: python3 tools/make_frost_layout.py
"""
import re

SOURCE = "tools/meadow_layout.gd"
TARGET = "tools/frost_layout.gd"

# old asset -> (new asset, height factor)
SWAPS = {
    "butcher/grass-tree-a": ("butcher/snow-tree-a", 1.6),
    "butcher/grass-tree-b": ("butcher/snow-tree-b", 1.6),
    "butcher/green-crystal": ("butcher/ice-crystal", 1.0),
    "butcher/desert-building": ("butcher/snow-house", 1.25),
    "butcher/camp-structure": ("butcher/snow-lodge", 1.1),
    "butcher/desert-cart": ("butcher/snow-crate", 0.6),
    "butcher/sand-wall": ("butcher/frozen-wall", 0.75),
    "stylized/haystack": ("butcher/snow-crate", 0.9),
    "stylized/tree-fruit": ("stylized/tree-pine", 1.0),
}


def fmt(v):
    v = round(v, 2)
    return ("%d" % v) if v == int(v) else ("%g" % v)


def mirror_vectors(text):
    text = re.sub(r"Vector2\((-?[\d.]+), (-?[\d.]+)\)", lambda m: "Vector2(%s, %s)" % (fmt(-float(m.group(1))), m.group(2)), text)
    text = re.sub(r"Vector3\((-?[\d.]+), (-?[\d.]+), (-?[\d.]+)\)", lambda m: "Vector3(%s, %s, %s)" % (fmt(-float(m.group(1))), m.group(2), m.group(3)), text)
    text = re.sub(r"Vector4\((-?[\d.]+), (-?[\d.]+), (-?[\d.]+), (-?[\d.]+)\)", lambda m: "Vector4(%s, %s, %s, %s)" % (fmt(-float(m.group(1))), m.group(2), m.group(3), m.group(4)), text)
    return text


def swap_props(text):
    def repl(m):
        asset, x, z, height, yaw, rest = m.group(1), float(m.group(2)), m.group(3), float(m.group(4)), float(m.group(5)), m.group(6)
        new_asset, factor = SWAPS.get(asset, (asset, 1.0))
        return '["%s", %s, %s, %s, %s%s' % (new_asset, fmt(-x), z, fmt(height * factor), fmt(-yaw), rest)
    return re.sub(r'\["([^"]+)", (-?[\d.]+), (-?[\d.]+), (-?[\d.]+), (-?[\d.]+)([,\]])', repl, text)


def main():
    text = open(SOURCE).read()
    pieces = re.split(r"(?m)^(?=const )", text)
    out = []
    for piece in pieces:
        m = re.match(r"const (\w+)", piece)
        name = m.group(1) if m else ""
        if name == "NORTH_NOTCH":
            a, b = re.search(r"Vector2\((-?[\d.]+), (-?[\d.]+)\)", piece).groups()
            piece = re.sub(r"Vector2\([^)]*\)", "Vector2(%s, %s)" % (fmt(-float(b)), fmt(-float(a))), piece)
        elif name == "EAST_NOTCH":
            piece = piece.replace("const EAST_NOTCH", "## z-range where the lake drains off the map (west side here).\nconst WATER_EXIT_WEST := true\nconst EAST_NOTCH")
        elif name == "SPAWN":
            piece = re.sub(r"Vector3\((-?[\d.]+), ", lambda m: "Vector3(%s, " % fmt(-float(m.group(1))), piece)
        elif name == "PLAZAS":
            piece = mirror_vectors(piece)
            # No Reaper or knights in region 2.
            piece = re.sub(r"\t# Start-area arenas.*?\n\tVector3\([^\n]*\n", "", piece, flags=re.S)
        elif name in ("FIELDS", "TRAINING_DUMMIES"):
            piece = re.sub(r"(const %s := )\[.*?\]\n" % name, r"\1[]\n", piece, flags=re.S) if name == "TRAINING_DUMMIES" else re.sub(r"const FIELDS := \[.*?\]\]\n", "const FIELDS := []\n", piece, flags=re.S)
        elif name == "LINK":
            piece = """## Gateway from the Meadowlands (D-102): the south border is a short band
## and a corridor at GATE_X runs to the clearing just inside.
const LINK := {"side": "south", "outer": 134.0, "gate_x": 0.0, "gate_half": 7.0,
	"path": [Vector2(0, 96.1), Vector2(0, 142)]}
"""
        elif name == "ORCHARD":
            piece = re.sub(r"\[Vector2\([^)]*\), \d+, \d+,", "[Vector2(0, 0), 0, 0,", piece)
        elif name in ("VILLAGE", "TERRACE_PROPS", "FOREST", "FARM", "POND_PROPS", "OUTER_GROUPS", "RAISED_GROUPS"):
            piece = swap_props(piece)
        else:
            piece = mirror_vectors(piece)
        out.append(piece)
    result = "".join(out)
    result = re.sub(r"(?m)^## Hand-authored layout data[^\n]*\n(##[^\n]*\n)*", "## Frostlands layout (region 2, D-100), generated by tools/make_frost_layout.py\n## from tools/meadow_layout.gd: the same ground plan mirrored left to right,\n## dressed for winter. Edit the generator, not this file.\n", result)
    open(TARGET, "w").write(result)


main()
