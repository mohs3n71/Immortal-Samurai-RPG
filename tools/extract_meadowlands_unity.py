"""Extract a static Meadowlands scene from the recovered Unity YAML export.

The source index must first be generated by index_butcher_meadowlands.py.
Only transforms, mesh filters and mesh renderers are retained. Gameplay scripts,
particles, colliders and other runtime components are deliberately excluded.
"""
import json
from pathlib import Path
import re

SOURCE = Path('../Butcher Hero/ButcherHeroReconstruction/unity_project/ExportedProject/Assets/Scenes/Main.unity')
INDEX = Path('assets/environment/butcher-meadowlands/scene-index.json')
DESTINATION = Path('unity-meadowlands/Assets/Scenes/MeadowlandsStatic.unity')


def main():
    objects = json.loads(INDEX.read_text(encoding='utf-8'))['objects']
    game_objects = {item['game_object_id'] for item in objects}
    text = SOURCE.read_text(encoding='utf-8')
    parts = re.split(r'(?m)(?=^--- !u!)', text)
    selected = []
    component_ids = set()
    for block in parts[1:]:
        header = re.match(r'--- !u!(\d+) &(\d+)', block)
        if not header:
            continue
        kind, object_id = map(int, header.groups())
        game_object = re.search(r'(?m)^  m_GameObject: \{fileID: (\d+)\}', block)
        include = (kind == 1 and object_id in game_objects) or (kind in (4, 23, 33) and game_object and int(game_object.group(1)) in game_objects)
        if include:
            selected.append((kind, object_id, block))
            if kind != 1:
                component_ids.add(object_id)
    output = [parts[0]]
    for kind, object_id, block in selected:
        if kind == 1:
            block = re.sub(r'(?m)^  - component: \{fileID: (\d+)\}\n',
                           lambda match: match.group(0) if int(match.group(1)) in component_ids else '', block)
        if kind == 4 and object_id == 17004:
            block = re.sub(r'(?m)^  m_Father: \{fileID: \d+\}', '  m_Father: {fileID: 0}', block)
        output.append(block)
    DESTINATION.write_text(''.join(output), encoding='utf-8')
    DESTINATION.with_suffix('.unity.meta').write_text('fileFormatVersion: 2\nguid: 7830901aef75485e8bc34aba02e0c101\n', encoding='utf-8')
    print(f'Wrote {DESTINATION}: {len(game_objects)} objects, {len(component_ids)} components')


if __name__ == '__main__':
    main()
